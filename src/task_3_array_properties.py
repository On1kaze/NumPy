"""
Задание 3: Свойства массива
Условие:
Для массива ниже определите без запуска программы значения ndim, shape, size и dtype.
Затем проверьте ответ в Python.

a = np.array([[3, 6, 9],
              [12, 15, 18]])
"""
import numpy as np


def run_task_3():
    print("=" * 50)
    print("Задание 3: Свойства массива")
    print("=" * 50)

    # Исходный массив
    a = np.array([[3, 6, 9],
                  [12, 15, 18]])

    # 1. Теоретический анализ (без запуска):
    theory = {
        "ndim": 2,          # 2 измерения (оси): строки и столбцы (двумерная матрица)
        "shape": (2, 3),    # 2 строки и 3 столбца
        "size": 6,          # Всего элементов: 2 * 3 = 6
        "dtype": "целочисленный тип (int32 или int64 в зависимости от ОС и разрядности)",
    }

    print("--- 1. Теоретический расчёт (без запуска программы) ---")
    print("• a.ndim  = 2     -> Двумерный массив (матрица: строки и столбцы)")
    print("• a.shape = (2, 3) -> 2 строки, 3 столбца")
    print("• a.size  = 6     -> Общее количество элементов (2 * 3 = 6)")
    print("• a.dtype = int32 / int64 -> Целые числа (по умолчанию)")

    print("\n--- 2. Практическая проверка в Python ---")
    print(f"• a.ndim:  {a.ndim}")
    print(f"• a.shape: {a.shape}")
    print(f"• a.size:  {a.size}")
    print(f"• a.dtype: {a.dtype}")
    print()

    # Сравнение теории и практики
    assert a.ndim == theory["ndim"], "ndim не совпадает!"
    assert a.shape == theory["shape"], "shape не совпадает!"
    assert a.size == theory["size"], "size не совпадает!"
    print("Все теоретические расчеты подтверждены!")
    print()

    return a, theory


if __name__ == "__main__":
    run_task_3()
